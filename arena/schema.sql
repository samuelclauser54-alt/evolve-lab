CREATE TABLE IF NOT EXISTS subs (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  name TEXT NOT NULL,
  w TEXT NOT NULL,
  whash TEXT NOT NULL UNIQUE,
  gen INTEGER NOT NULL,
  score INTEGER NOT NULL,
  day TEXT NOT NULL,
  iph TEXT NOT NULL,
  hidden INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS subs_score ON subs (hidden, score DESC, id);
CREATE INDEX IF NOT EXISTS subs_ip ON subs (iph, day);
CREATE TABLE IF NOT EXISTS counts (day TEXT PRIMARY KEY, loads INTEGER NOT NULL DEFAULT 0, subs INTEGER NOT NULL DEFAULT 0, gens INTEGER NOT NULL DEFAULT 0);
